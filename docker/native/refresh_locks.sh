#!/bin/sh
# Regenerate the exact Wolfi package locks from the current repository index.
#
# Run from the repository root on an x86_64 Docker host:
#
#     sh docker/native/refresh_locks.sh
#
# The script installs the package names from each lock, without versions, into
# the pinned Wolfi base image and records what was actually installed, including
# new dependencies. Afterwards rebuild every image target, run the CI image scans
# and review the lock diff before committing it.
set -eu

if [ "${1:-}" != "--inside" ]; then
    base=$(sed -n 's/^FROM \(cgr\.dev\/chainguard\/wolfi-base[^ ]*\) AS native-base$/\1/p' Dockerfile)
    if [ -z "$base" ]; then
        echo "Could not find the native-base image in Dockerfile" >&2
        exit 1
    fi
    exec docker run --rm -v "$PWD/docker/native:/native" "$base" sh /native/refresh_locks.sh --inside
fi

cd /native
today=$(date -u +%Y-%m-%d)

names() {
    awk '{sub(/\r$/, "")} NF && !/^[#!]/ {sub(/[=@].*/, ""); print}' "$1"
}

constraints() {
    awk '{sub(/\r$/, "")} /^!/' "$1"
}

inventory() {
    awk '/^P:/ {name = substr($0, 3)} /^V:/ {print name "=" substr($0, 3)}' /lib/apk/db/installed \
        | LC_ALL=C sort
}

write_lock() {
    lock=$1
    description=$2
    {
        echo "# $description Generated by docker/native/refresh_locks.sh on $today."
        inventory
        constraints "$lock"
    } > "$lock.new"
    mv "$lock.new" "$lock"
}

# The base image's world file pins its own packages to the versions it was built
# with, which `apk upgrade` respects. The Dockerfile installs exact versions on
# top of it and so upgrades them; unpin them here to resolve the same way.
sed -i 's/=.*//' /etc/apk/world
apk upgrade --no-cache
# shellcheck disable=SC2046 # package names are word-split on purpose
apk add --no-cache $(names api.apk.lock)
write_lock api.apk.lock "Wolfi x86_64 runtime shared by the API and worker images."
# shellcheck disable=SC2046
apk add --no-cache $(names worker.apk.lock) $(constraints worker.apk.lock)
write_lock worker.apk.lock "Wolfi x86_64 runtime of the browser worker image."
echo "Updated api.apk.lock and worker.apk.lock; rebuild the images and scan them."
